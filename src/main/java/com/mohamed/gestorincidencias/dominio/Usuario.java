package com.mohamed.gestorincidencias.dominio;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;

import java.time.Instant;

/**
 * Persona que reporta incidencias o las tiene asignadas. Mapea la tabla "usuario" de V1.
 */
@Entity
@Table(name = "usuario")
public class Usuario {

    // IDENTITY: el id lo genera PostgreSQL (columna GENERATED BY DEFAULT AS IDENTITY).
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 100)
    private String nombre;

    @Column(nullable = false, length = 150, unique = true)
    private String email;

    // STRING guarda el nombre del valor ("TECNICO"), no su posición (ORDINAL = 0, 1, 2...).
    // Con ORDINAL, reordenar el enum corrompería los datos y además no encajaría con el CHECK.
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Rol rol;

    // Baja lógica: un usuario con incidencias no se puede borrar (FK sin ON DELETE), se desactiva.
    @Column(nullable = false)
    private boolean activo;

    // TIMESTAMPTZ representa un instante absoluto: en Java el tipo equivalente es Instant.
    @Column(name = "fecha_creacion", nullable = false, updatable = false)
    private Instant fechaCreacion;

    // JPA exige un constructor sin argumentos; protected para que el resto del código no lo use.
    protected Usuario() {
    }

    public Usuario(String nombre, String email, Rol rol) {
        this.nombre = nombre;
        this.email = email;
        this.rol = rol;
        this.activo = true;
    }

    @PrePersist
    void alCrear() {
        this.fechaCreacion = Instant.now();
    }

    public Long getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public String getEmail() {
        return email;
    }

    public Rol getRol() {
        return rol;
    }

    public boolean isActivo() {
        return activo;
    }

    public Instant getFechaCreacion() {
        return fechaCreacion;
    }
}
