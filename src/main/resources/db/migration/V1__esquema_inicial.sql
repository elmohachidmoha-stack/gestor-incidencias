-- =====================================================================
-- V1: esquema inicial del gestor de incidencias
-- Tablas: usuario, incidencia, historial_incidencia
-- Una migración ya aplicada NO se edita nunca: los cambios van en V3, V4...
-- =====================================================================

-- ---------------------------------------------------------------------
-- usuario: personas que crean incidencias o las tienen asignadas.
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    -- IDENTITY es el estándar SQL para autoincrementales (sustituye a SERIAL).
    -- BY DEFAULT permite insertar un id explícito si alguna vez hace falta (p. ej. al restaurar datos).
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    rol            VARCHAR(20)  NOT NULL DEFAULT 'USUARIO',
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    -- TIMESTAMPTZ guarda el instante exacto (en UTC internamente), independiente de la zona horaria.
    fecha_creacion TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- El UNIQUE crea automáticamente un índice sobre email.
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'TECNICO', 'USUARIO'))
);

-- ---------------------------------------------------------------------
-- incidencia: el elemento central de la aplicación.
-- ---------------------------------------------------------------------
CREATE TABLE incidencia (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo              VARCHAR(150) NOT NULL,
    descripcion         TEXT,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'ABIERTA',
    prioridad           VARCHAR(10)  NOT NULL DEFAULT 'MEDIA',
    -- Quién la abrió (obligatorio) y quién la está resolviendo (puede no haber nadie aún).
    creador_id          BIGINT       NOT NULL,
    asignado_id         BIGINT,
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Los CHECK son la última línea de defensa: aunque la API valide, la BD nunca acepta
    -- un estado o prioridad inventados (p. ej. desde un script SQL manual).
    CONSTRAINT ck_incidencia_estado
        CHECK (estado IN ('ABIERTA', 'EN_PROGRESO', 'RESUELTA', 'CERRADA')),
    CONSTRAINT ck_incidencia_prioridad
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_incidencia_titulo_no_vacio
        CHECK (length(trim(titulo)) > 0),

    -- Sin ON DELETE: por defecto es RESTRICT, no se puede borrar un usuario con incidencias.
    -- Así no se pierde información; para "dar de baja" a un usuario se usa activo = FALSE.
    CONSTRAINT fk_incidencia_creador  FOREIGN KEY (creador_id)  REFERENCES usuario (id),
    CONSTRAINT fk_incidencia_asignado FOREIGN KEY (asignado_id) REFERENCES usuario (id)
);

-- PostgreSQL NO crea índices automáticamente en las claves foráneas: los creamos nosotros.
-- Aceleran los JOIN y las búsquedas "incidencias de un usuario".
CREATE INDEX idx_incidencia_creador  ON incidencia (creador_id);
CREATE INDEX idx_incidencia_asignado ON incidencia (asignado_id);
-- Estado y prioridad serán los filtros más habituales del listado (Día 6).
CREATE INDEX idx_incidencia_estado    ON incidencia (estado);
CREATE INDEX idx_incidencia_prioridad ON incidencia (prioridad);

-- ---------------------------------------------------------------------
-- historial_incidencia: registro de cada cambio (estado, prioridad, asignación).
-- Diseño genérico campo / valor_anterior / valor_nuevo: sirve para cualquier
-- campo sin tener que añadir columnas nuevas.
-- ---------------------------------------------------------------------
CREATE TABLE historial_incidencia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id  BIGINT       NOT NULL,
    -- Usuario que hizo el cambio.
    usuario_id     BIGINT       NOT NULL,
    campo          VARCHAR(30)  NOT NULL,
    valor_anterior VARCHAR(255),
    valor_nuevo    VARCHAR(255),
    fecha_cambio   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_historial_campo CHECK (campo IN ('ESTADO', 'PRIORIDAD', 'ASIGNADO')),
    -- El historial pertenece a la incidencia: si se borra la incidencia, se borra su historial.
    CONSTRAINT fk_historial_incidencia FOREIGN KEY (incidencia_id)
        REFERENCES incidencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_historial_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

-- Consulta típica: "historial de la incidencia X ordenado por fecha". Un índice compuesto
-- resuelve el filtro y el orden a la vez.
CREATE INDEX idx_historial_incidencia_fecha ON historial_incidencia (incidencia_id, fecha_cambio);
CREATE INDEX idx_historial_usuario ON historial_incidencia (usuario_id);
